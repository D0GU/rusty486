//! Generates bios/font8x8.inc (CP437 8x8 glyphs, bit 0 = leftmost pixel) and
//! bios/palette.inc (the default 256-colour DAC palette) for the BIOS ROM.
//!
//!   cargo run -p rusty486-sdl --example gen_bios_data

#[path = "../src/font.rs"]
mod font;

use std::fmt::Write;

fn main() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../bios");
    let mut f = String::from("; Generated by crates/sdl/examples/gen_bios_data.rs - do not edit.\n");
    f.push_str("; CP437 8x8 font from the public-domain font8x8 set (bit 0 = leftmost pixel).\n");
    for (i, g) in font::cp437().iter().enumerate() {
        let bytes: Vec<String> = g.iter().map(|b| format!("0x{b:02X}")).collect();
        writeln!(f, "        db {}  ; {i:02X}", bytes.join(", ")).unwrap();
    }
    std::fs::write(root.join("font8x8.inc"), f).unwrap();

    let pal = rusty486_core::devices::video::default_palette();
    let mut p = String::from("; Generated by crates/sdl/examples/gen_bios_data.rs - do not edit.\n");
    p.push_str("; Default DAC palette: 16 EGA colours, 16 greys, 6x6x6 cube (6-bit RGB).\n");
    for chunk in pal.chunks(24) {
        let bytes: Vec<String> = chunk.iter().map(|b| format!("{b}")).collect();
        writeln!(p, "        db {}", bytes.join(", ")).unwrap();
    }
    std::fs::write(root.join("palette.inc"), p).unwrap();
    println!("wrote bios/font8x8.inc and bios/palette.inc");
}
